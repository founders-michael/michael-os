"use client";

import Link from "next/link";
import type { ReactNode } from "react";
import { ArrowRight, ChevronDown, Clock3, LoaderCircle, MessageCircle, RefreshCw } from "lucide-react";
import { Collapsible } from "@animate-ui/react/primitives/radix-ui";
import { SlidingNumber } from "@animate-ui/react/primitives/texts/sliding-number";
import MichaelPresence from "@/components/michael/michael-presence";
import MichaelAmbient from "@/components/michael/michael-ambient";
import type { HomeAskPrompt } from "@/lib/my-day-model";

/** A count shown in the hero; `null` when its source could not be loaded. */
export type HeroStat = { label: string; value: number | null; of?: number | null };

/**
 * A number that was right on first paint and slides when it changes — after a
 * habit is checked off, or a task completed. `initiallyStable` is essential:
 * without it the counter renders 0 on the server and counts up, briefly
 * showing a wrong figure.
 */
function StatValue({ value }: { value: number }) {
  return <SlidingNumber number={value} initiallyStable />;
}

/**
 * The top of Home: Michael, the user's day in one line, and what to ask next.
 *
 * Everything in it is computed from the user's saved data by the existing,
 * tested helpers in `my-day-model.ts` — the greeting on the user's own clock,
 * the briefing from real counts, the prompts from the same counts. None of it
 * is generated by a model: the page must not spend a model turn, or send the
 * user's data anywhere, just because it was opened. The prompts only open the
 * assistant with a question filled in.
 */
export default function MichaelHomeHero({ greeting, name, dateLabel, timeZone, wakeUpTime, focusSessionMinutes, briefing, stats, basis, prompts, refreshing, onRefresh }: {
  greeting: string;
  name: string;
  dateLabel: string;
  timeZone: string;
  wakeUpTime: string;
  focusSessionMinutes: number;
  briefing: string;
  stats: HeroStat[];
  basis: ReactNode;
  prompts: HomeAskPrompt[];
  refreshing: boolean;
  onRefresh: () => void;
}) {
  return (
    <section className="michael-home-hero" aria-labelledby="michael-home-greeting">
      <MichaelAmbient />
      <div className="michael-home-hero-inner">
        <div className="michael-home-meta">
          <div className="my-day-date"><span className="my-day-date-dot" />{dateLabel} <span>· {timeZone}</span></div>
          <div className="my-day-header-actions">
            <span className="my-day-rhythm"><Clock3 size={14} />Wake {wakeUpTime} <i /> {focusSessionMinutes} min focus</span>
            <button className="my-day-refresh" type="button" onClick={onRefresh} disabled={refreshing} aria-label="Refresh today's overview">
              {refreshing ? <LoaderCircle className="my-day-spin" size={16} /> : <RefreshCw size={16} />}
              <span>{refreshing ? "Refreshing" : "Refresh"}</span>
            </button>
          </div>
        </div>

        <div className="michael-home-body">
          <MichaelPresence state="idle" size="xl" className="michael-home-presence" />
          <div className="michael-home-copy">
            <h1 id="michael-home-greeting">{greeting}, {name}</h1>
            <p className="michael-home-briefing"><span className="michael-home-voice">Michael</span>{briefing}</p>

            <ul className="michael-home-stats" aria-label="Today at a glance">
              {stats.map((stat) => (
                <li key={stat.label}>
                  <strong>
                    {stat.value === null ? "—" : <StatValue value={stat.value} />}
                    {stat.of !== undefined && <small>/{stat.of === null ? "—" : <StatValue value={stat.of} />}</small>}
                  </strong>
                  {stat.label}
                </li>
              ))}
            </ul>

            <Collapsible.Root className="michael-home-basis">
              <Collapsible.Trigger className="michael-home-basis-trigger">
                See what this is based on <ChevronDown className="michael-home-basis-chevron" size={14} aria-hidden="true" />
              </Collapsible.Trigger>
              <Collapsible.Content className="michael-home-basis-content">{basis}</Collapsible.Content>
            </Collapsible.Root>

            {prompts.length > 0 && (
              <nav className="michael-home-prompts" aria-label="Ask Michael about your day">
                {prompts.map((prompt) => (
                  <Link key={prompt.href} href={prompt.href} className="michael-home-prompt">
                    <MessageCircle size={14} aria-hidden="true" />
                    <span>{prompt.label}</span>
                    <ArrowRight size={14} aria-hidden="true" />
                  </Link>
                ))}
              </nav>
            )}
          </div>
        </div>
      </div>
    </section>
  );
}
