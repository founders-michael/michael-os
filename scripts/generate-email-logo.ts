/**
 * Regenerates src/emails/assets/michael-logo.ts from michael-logo.png, so the
 * logo ships inside the server bundle (a deployed function may not have src/ on
 * disk). Run after replacing the PNG: `npx tsx scripts/generate-email-logo.ts`.
 */
import { readFile, writeFile } from "node:fs/promises";

const png = await readFile("src/emails/assets/michael-logo.png");
await writeFile("src/emails/assets/michael-logo.ts", `// Generated by scripts/generate-email-logo.ts from michael-logo.png (440×86). Do not edit by hand.\nexport const MICHAEL_LOGO_PNG_BASE64 =\n  "${png.toString("base64")}";\n`);
console.log(`michael-logo.ts written (${png.length} bytes of PNG)`);
